"""Canonical Kafka event envelope for all Encore services.

Every message published to any Kafka topic MUST wrap its payload in this
envelope. Conventions are documented in:
  docs/architecture/kafka-conventions.md §2

FIELDS:
  event_id       Snowflake ID of the event itself (not the entity it's about).
                 Generated by the producer at publish time.
  event_type     Dot-separated topic path, e.g. "inventory.seat.held".
                 Matches the Kafka topic name.
  event_version  Integer schema version of the *payload*. Bump this —
                 not event_type — when the payload shape changes in a
                 backward-incompatible way. Consumers check this field and
                 route to DLQ if they receive a version they don't handle.
  occurred_at    ISO 8601 UTC timestamp of when the underlying fact occurred
                 (e.g. when the DB row was committed), not when the message
                 was published.
  trace_id       The originating HTTP request's X-Request-Id. Used for
                 cross-service tracing before a dedicated tracing layer
                 (Jaeger / OTEL) lands in Week 15.
  producer       Name of the emitting service, e.g. "api-gateway".
  key            Kafka partition key (also echoed in the envelope body for
                 consumer convenience — see kafka-conventions.md §3).
  payload        Event-specific dictionary. Typed by each event module.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from typing import Any


@dataclass
class EventEnvelope:
    """The standard wrapper for every Kafka message in Encore."""

    event_id: str
    event_type: str
    event_version: int
    occurred_at: str        # ISO 8601 UTC, e.g. "2026-08-27T18:00:00.000Z"
    trace_id: str
    producer: str
    key: str                # Kafka partition key
    payload: dict[str, Any]

    # ------------------------------------------------------------------ serialisation

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-serialisable dictionary."""
        return asdict(self)

    def to_json(self) -> str:
        """Serialise to a compact JSON string (Kafka message value)."""
        return json.dumps(self.to_dict(), separators=(",", ":"))

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "EventEnvelope":
        """Deserialise from a dict (e.g. after JSON parsing a Kafka message)."""
        return cls(
            event_id=data["event_id"],
            event_type=data["event_type"],
            event_version=int(data["event_version"]),
            occurred_at=data["occurred_at"],
            trace_id=data["trace_id"],
            producer=data["producer"],
            key=data["key"],
            payload=data["payload"],
        )

    @classmethod
    def from_json(cls, raw: str | bytes) -> "EventEnvelope":
        """Deserialise from a JSON bytes/string (Kafka message value)."""
        return cls.from_dict(json.loads(raw))
