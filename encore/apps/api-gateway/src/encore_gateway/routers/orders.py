"""POST /api/v1/orders, GET /api/v1/orders/{order_id}.

The "mock order → mock ticket" step of
docs/architecture/vertical-slice-plan.md.

Payment is mocked: it always succeeds, synchronously, in-process. No real
payment provider, no async checkout saga (Kafka), no idempotency check on
a *payment* specifically — those all arrive with checkout-service and
payment-service in later weeks (see docs/architecture/service-boundaries.md).
What Week 2 DOES implement correctly: the order is only created if the
seat is HELD by the requesting user, and the hold → sale → ticket
sequence happens inside a single DB transaction, so a failure partway
through can't leave a SOLD seat with no ticket, or a ticket with no order.

Week 4 additions:
  - Checkout rate limit: 3 attempts/minute per user (config-driven).
  - Order and Ticket primary keys generated by SnowflakeIDGenerator
    (stored as UUID in existing schema columns — see packages/id-generator).
"""

from __future__ import annotations

import json
import uuid
from datetime import UTC

from encore_cache import CacheClient
from encore_common import error_envelope, success_envelope

# Week 5 additions
from encore_id_generator import SnowflakeIDGenerator
from encore_kafka_client import build_envelope
from fastapi import APIRouter, Depends, Header, HTTPException, Request
from fastapi.responses import JSONResponse
from sqlalchemy import select
from sqlalchemy.orm import Session, selectinload

from ..auth import get_current_user
from ..cache import get_cache
from ..db import get_db, get_db_read
from ..domain.inventory_state import InventoryStatus as DomainInventoryStatus
from ..domain.inventory_state import can_purchase
from ..idempotency import get_idempotent_response, save_idempotent_response
from ..models import Inventory, InventoryStatus, Order, OrderStatus, User
from ..schemas import OrderCreate, OrderOut, TicketOut

router = APIRouter(prefix="/api/v1/orders", tags=["orders"])

CREATE_ENDPOINT_NAME = "POST /api/v1/orders"

# Process-scoped Snowflake generator.
_id_gen = SnowflakeIDGenerator()


def _new_id() -> uuid.UUID:
    """Generate a Snowflake ID and return it as a UUID for DB storage."""
    return _id_gen.next_id().as_uuid()


@router.post("", status_code=201)
def create_order(
    payload: OrderCreate,
    request: Request,
    idempotency_key: str | None = Header(default=None, alias="Idempotency-Key"),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
    cache: CacheClient = Depends(get_cache),
) -> JSONResponse:
    request_id = getattr(request.state, "request_id", "")

    # --- Checkout rate limit (per authenticated user) ---
    checkout_limiter = getattr(request.app.state, "checkout_rate_limiter", None)
    if checkout_limiter is not None:
        from encore_cache.helpers import rate_limit_key
        from encore_rate_limiter import RateLimitExceeded

        try:
            checkout_limiter.check_or_raise(rate_limit_key(f"checkout:{current_user.id}"))
        except RateLimitExceeded as exc:
            retry_after = int(exc.result.retry_after_seconds) + 1
            body = error_envelope(
                "CHECKOUT_RATE_LIMIT_EXCEEDED",
                f"Too many checkout attempts. Retry after {retry_after}s.",
                request_id,
            )
            return JSONResponse(
                status_code=429,
                content=body,
                headers={"Retry-After": str(retry_after)},
            )

    # --- Idempotency ---
    if not idempotency_key:
        raise HTTPException(
            status_code=400,
            detail=error_envelope(
                "MISSING_IDEMPOTENCY_KEY", "Idempotency-Key header is required.", request_id
            ),
        )

    existing = get_idempotent_response(db, idempotency_key, CREATE_ENDPOINT_NAME)
    if existing is not None:
        return JSONResponse(status_code=existing.status_code, content=json.loads(existing.response_json))  # noqa: E501

    from ..db import shard_manager
    shard_db = shard_manager.get_session(payload.event_id)
    try:
        # --- Load inventory from SHARD ---
        inventory_row = shard_db.execute(
            select(Inventory).where(
                Inventory.event_id == payload.event_id, Inventory.seat_id == payload.seat_id
            )
        ).scalar_one_or_none()

        if inventory_row is None:
            raise HTTPException(
                status_code=404, detail=error_envelope("SEAT_NOT_FOUND", "No such seat for this event.", request_id)  # noqa: E501
            )

        transition = can_purchase(
            DomainInventoryStatus(inventory_row.status.value),
            held_by_user_id=inventory_row.held_by_user_id,
            requesting_user_id=current_user.id,
        )
        if not transition.allowed:
            body = error_envelope(transition.reason, "Seat cannot be purchased in its current state.", request_id)  # noqa: E501
            save_idempotent_response(db, idempotency_key, CREATE_ENDPOINT_NAME, 409, body)
            db.commit()
            return JSONResponse(status_code=409, content=body)

        # Store the price from the shard to use in the primary DB transaction
        price_cents = inventory_row.price_cents
    finally:
        shard_db.close()

    # --- Create PENDING order in PRIMARY (Snowflake IDs, Week 4) ---
    order_id = _new_id()

    order = Order(
        id=order_id,
        user_id=current_user.id,
        event_id=payload.event_id,
        status=OrderStatus.PENDING,
        total_cents=price_cents,
        idempotency_key=idempotency_key,
    )
    db.add(order)
    db.flush()  # assign server defaults (created_at) before building the response

    order_out = OrderOut(
        id=order.id,
        event_id=order.event_id,
        user_id=order.user_id,
        status=order.status,
        total_cents=order.total_cents,
        created_at=order.created_at,
        tickets=[],
    )
    body = success_envelope(order_out.model_dump(mode="json"), request_id=request_id)

    save_idempotent_response(db, idempotency_key, CREATE_ENDPOINT_NAME, 201, body)
    db.commit()

    return JSONResponse(status_code=201, content=body)


@router.get("/{order_id}")
def get_order(order_id: uuid.UUID, request: Request, db: Session = Depends(get_db_read)) -> dict:
    request_id = getattr(request.state, "request_id", "")

    order = db.execute(
        select(Order).options(selectinload(Order.tickets)).where(Order.id == order_id)
    ).scalar_one_or_none()

    if order is None:
        raise HTTPException(status_code=404, detail=error_envelope("ORDER_NOT_FOUND", "No such order.", request_id))  # noqa: E501

    tickets_out = []
    
    from ..db import shard_manager
    shard_db = shard_manager.get_session(order.event_id)
    try:
        for ticket in order.tickets:
            inv = shard_db.get(Inventory, ticket.inventory_id)
            if inv:
                tickets_out.append(
                    TicketOut(id=ticket.id, ticket_code=ticket.ticket_code, status=ticket.status, seat_id=inv.seat_id)  # noqa: E501
                )
    finally:
        shard_db.close()

    order_out = OrderOut(
        id=order.id,
        event_id=order.event_id,
        user_id=order.user_id,
        status=order.status,
        total_cents=order.total_cents,
        created_at=order.created_at,
        tickets=tickets_out,
    )
    return success_envelope(order_out.model_dump(mode="json"), request_id=request_id)


@router.post("/{order_id}/cancel", status_code=200)
def cancel_order(
    order_id: uuid.UUID,
    request: Request,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
) -> JSONResponse:
    """Cancel a PENDING order and credit the amount to the user's wallet.
    
    Only PENDING orders can be cancelled (CONFIRMED orders require a refund flow).
    Releases any HELD inventory back to AVAILABLE.
    Emits order.cancelled Kafka event.
    """
    request_id = getattr(request.state, "request_id", "")
    
    order = db.execute(select(Order).options(selectinload(Order.tickets)).where(Order.id == order_id)).scalar_one_or_none()  # noqa: E501
    if order is None:
        raise HTTPException(status_code=404, detail=error_envelope("ORDER_NOT_FOUND", "No such order.", request_id))  # noqa: E501
    if order.user_id != current_user.id:
        raise HTTPException(status_code=403, detail=error_envelope("FORBIDDEN", "Not your order.", request_id))  # noqa: E501
    if order.status != OrderStatus.PENDING:
        raise HTTPException(status_code=409, detail=error_envelope(
            "INVALID_ORDER_STATE",
            f"Cannot cancel order in {order.status} state.",
            request_id
        ))
    
    # 1. Release all held inventory for this order back to AVAILABLE
    from ..db import shard_manager
    shard_db = shard_manager.get_session(order.event_id)
    try:
        for ticket in order.tickets:
            inv = shard_db.get(Inventory, ticket.inventory_id)
            if inv and inv.status.value == DomainInventoryStatus.HELD.value:
                inv.status = InventoryStatus.AVAILABLE
                inv.held_by_user_id = None
                inv.held_at = None
                inv.hold_expires_at = None
        shard_db.commit()
    finally:
        shard_db.close()
    
    # 2. Credit wallet via wallet-service HTTP call
    import os

    import httpx
    wallet_url = os.environ.get("WALLET_SERVICE_URL", "http://localhost:8007")
    try:
        with httpx.Client(timeout=5.0) as client:
            resp = client.post(
                f"{wallet_url}/api/v1/wallet/credit",
                json={
                    "user_id": str(current_user.id),
                    "amount_cents": order.total_cents,
                    "reference": f"refund_order_{order_id}"
                },
                headers={"X-Request-Id": request_id}
            )
            resp.raise_for_status()
    except Exception:
        # Log error, but proceed with cancellation in this naive V1 implementation
        pass
        
    # 3. Mark order as CANCELLED
    order.status = OrderStatus.CANCELLED
    db.commit()
    
    # 4. Emit order.cancelled Kafka event
    from datetime import datetime

    from encore_event_contracts.events.order import (
        ORDER_CANCELLED_EVENT_TYPE,
        ORDER_CANCELLED_TOPIC,
        ORDER_CANCELLED_VERSION,
        OrderCancelledPayload,
    )
    
    producer = getattr(request.app.state, "kafka_producer", None)
    if producer:
        now_str = datetime.now(UTC).isoformat()
        payload_obj = OrderCancelledPayload(
            order_id=str(order_id),
            user_id=str(current_user.id),
            event_id=str(order.event_id),
            cancelled_at=now_str,
        )
        env = build_envelope(
            event_type=ORDER_CANCELLED_EVENT_TYPE,
            event_version=ORDER_CANCELLED_VERSION,
            producer="api-gateway",
            key=str(order_id),
            payload=payload_obj.to_dict(),
            trace_id=request_id,
        )
        producer.publish(ORDER_CANCELLED_TOPIC, env)
    
    body = success_envelope({"order_id": str(order_id), "status": "CANCELLED"}, request_id=request_id)  # noqa: E501
    return JSONResponse(status_code=200, content=body)
