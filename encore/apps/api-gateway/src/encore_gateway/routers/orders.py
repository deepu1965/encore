router = APIRouter(prefix="/api/v1/orders", tags=["orders"])

CREATE_ENDPOINT_NAME = "POST /api/v1/orders"

# Process-scoped Snowflake generator.
_id_gen = SnowflakeIDGenerator()


def _new_id() -> uuid.UUID:
    """Generate a Snowflake ID and return it as a UUID for DB storage."""
    return _id_gen.next_id().as_uuid()


@router.post("", status_code=201)
def create_order(
    payload: OrderCreate,
    request: Request,
    idempotency_key: str | None = Header(default=None, alias="Idempotency-Key"),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
    cache: CacheClient = Depends(get_cache),
) -> JSONResponse:
    request_id = getattr(request.state, "request_id", "")

    # --- Checkout rate limit (per authenticated user) ---
    checkout_limiter = getattr(request.app.state, "checkout_rate_limiter", None)
    if checkout_limiter is not None:
        from encore_cache.helpers import rate_limit_key
        from encore_rate_limiter import RateLimitExceeded

        try:
            checkout_limiter.check_or_raise(rate_limit_key(f"checkout:{current_user.id}"))
        except RateLimitExceeded as exc:
            retry_after = int(exc.result.retry_after_seconds) + 1
            body = error_envelope(
                "CHECKOUT_RATE_LIMIT_EXCEEDED",
                f"Too many checkout attempts. Retry after {retry_after}s.",
                request_id,
            )
            return JSONResponse(
                status_code=429,
                content=body,
                headers={"Retry-After": str(retry_after)},
            )

    # --- Idempotency ---
    if not idempotency_key:
        raise HTTPException(
            status_code=400,
            detail=error_envelope(
                "MISSING_IDEMPOTENCY_KEY", "Idempotency-Key header is required.", request_id
            ),
        )

    existing = get_idempotent_response(db, idempotency_key, CREATE_ENDPOINT_NAME)
    if existing is not None:
        return JSONResponse(status_code=existing.status_code, content=json.loads(existing.response_json))

    from ..db import shard_manager
    shard_db = shard_manager.get_session(payload.event_id)
    try:
        # --- Load inventory from SHARD ---
        inventory_row = shard_db.execute(
            select(Inventory).where(
                Inventory.event_id == payload.event_id, Inventory.seat_id == payload.seat_id
            )
        ).scalar_one_or_none()

        if inventory_row is None:
            raise HTTPException(
                status_code=404, detail=error_envelope("SEAT_NOT_FOUND", "No such seat for this event.", request_id)
            )

        transition = can_purchase(
            DomainInventoryStatus(inventory_row.status.value),
            held_by_user_id=inventory_row.held_by_user_id,
            requesting_user_id=current_user.id,
        )
        if not transition.allowed:
            body = error_envelope(transition.reason, "Seat cannot be purchased in its current state.", request_id)
            save_idempotent_response(db, idempotency_key, CREATE_ENDPOINT_NAME, 409, body)
            db.commit()
            return JSONResponse(status_code=409, content=body)

        # Store the price from the shard to use in the primary DB transaction
        price_cents = inventory_row.price_cents
    finally:
        shard_db.close()

    # --- Create PENDING order in PRIMARY (Snowflake IDs, Week 4) ---
    order_id = _new_id()

    order = Order(
        id=order_id,
        user_id=current_user.id,
        event_id=payload.event_id,
        status=OrderStatus.PENDING,
        total_cents=price_cents,
        idempotency_key=idempotency_key,
    )
    db.add(order)
    db.flush()  # assign server defaults (created_at) before building the response

    order_out = OrderOut(
        id=order.id,
        event_id=order.event_id,
        user_id=order.user_id,
        status=order.status,
        total_cents=order.total_cents,
        created_at=order.created_at,
        tickets=[],
    )
    body = success_envelope(order_out.model_dump(mode="json"), request_id=request_id)

    save_idempotent_response(db, idempotency_key, CREATE_ENDPOINT_NAME, 201, body)
    db.commit()

    return JSONResponse(status_code=201, content=body)


@router.get("/{order_id}")
def get_order(order_id: uuid.UUID, request: Request, db: Session = Depends(get_db_read)) -> dict:
    request_id = getattr(request.state, "request_id", "")

    order = db.execute(
        select(Order).options(selectinload(Order.tickets)).where(Order.id == order_id)
    ).scalar_one_or_none()

    if order is None:
        raise HTTPException(status_code=404, detail=error_envelope("ORDER_NOT_FOUND", "No such order.", request_id))

    tickets_out = []
    
    from ..db import shard_manager
    shard_db = shard_manager.get_session(order.event_id)
    try:
        for ticket in order.tickets:
            inv = shard_db.get(Inventory, ticket.inventory_id)
            if inv:
                tickets_out.append(
                    TicketOut(id=ticket.id, ticket_code=ticket.ticket_code, status=ticket.status, seat_id=inv.seat_id)
                )
    finally:
        shard_db.close()

    order_out = OrderOut(
        id=order.id,
        event_id=order.event_id,
        user_id=order.user_id,
        status=order.status,
        total_cents=order.total_cents,
        created_at=order.created_at,
        tickets=tickets_out,
    )
    return success_envelope(order_out.model_dump(mode="json"), request_id=request_id)
